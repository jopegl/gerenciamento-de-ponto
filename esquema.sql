-- ---------------------------------------------------------------------
-- RN09 + RN11 (Pausa)
--   RN09: pausa só pode ser CRIADA se o ponto tiver entrada em aberto
--   RN11: pausa não pode começar antes da entrada registrada
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_valida_pausa() RETURNS TRIGGER AS $$
DECLARE v_entrada TIME;
v_saida TIME;
BEGIN
SELECT hora_entrada,
    hora_saida INTO v_entrada,
    v_saida
FROM Ponto
WHERE id_registro = NEW.id_registro;
IF TG_OP = 'INSERT'
AND v_saida IS NOT NULL THEN RAISE EXCEPTION 'RN09: o ponto % não possui entrada em aberto (saída já registrada às %).',
NEW.id_registro,
v_saida;
END IF;
IF NEW.hora_inicio < v_entrada THEN RAISE EXCEPTION 'RN11: a pausa (%) não pode começar antes da entrada (%).',
NEW.hora_inicio,
v_entrada;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_valida_pausa BEFORE
INSERT
    OR
UPDATE OF hora_inicio,
    id_registro ON Pausa FOR EACH ROW EXECUTE FUNCTION fn_valida_pausa();
-- RN11 (lado do Ponto): alterar a entrada não pode deixar pausas antes dela
CREATE OR REPLACE FUNCTION fn_valida_entrada_ponto() RETURNS TRIGGER AS $$ BEGIN IF EXISTS (
        SELECT 1
        FROM Pausa
        WHERE id_registro = NEW.id_registro
            AND hora_inicio < NEW.hora_entrada
    ) THEN RAISE EXCEPTION 'RN11: o ponto % possui pausa iniciada antes da nova entrada (%).',
    NEW.id_registro,
    NEW.hora_entrada;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_valida_entrada_ponto BEFORE
UPDATE OF hora_entrada ON Ponto FOR EACH ROW EXECUTE FUNCTION fn_valida_entrada_ponto();
-- ---------------------------------------------------------------------
-- RN14: períodos de ausência do mesmo funcionário não podem se sobrepor
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_valida_periodo_ausencia() RETURNS TRIGGER AS $$ BEGIN IF EXISTS (
        SELECT 1
        FROM Periodo_Ausencia p
        WHERE p.id_funcionario = NEW.id_funcionario
            AND p.id_periodo <> NEW.id_periodo
            AND p.data_inicio <= NEW.data_fim
            AND p.data_fim >= NEW.data_inicio
    ) THEN RAISE EXCEPTION 'RN14: o período de % a % se sobrepõe a outro período do funcionário %.',
    NEW.data_inicio,
    NEW.data_fim,
    NEW.id_funcionario;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_valida_periodo_ausencia BEFORE
INSERT
    OR
UPDATE OF data_inicio,
    data_fim,
    id_funcionario ON Periodo_Ausencia FOR EACH ROW EXECUTE FUNCTION fn_valida_periodo_ausencia();
-- ---------------------------------------------------------------------
-- RN12 + "duas escalas no mesmo dia da semana"
--   Função auxiliar que valida um funcionário:
--     a) não ter duas escalas no mesmo dia da semana
--     b) soma das escalas <= 50h semanais
--     c) soma das escalas > 0 (só depois que ele já tem escala)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_checa_escalas_funcionario(p_func INT, p_checa_minimo BOOLEAN) RETURNS VOID AS $$
DECLARE v_dia VARCHAR;
v_horas NUMERIC;
BEGIN
SELECT e.dia_semana INTO v_dia
FROM Cumpre c
    JOIN Escala_Trabalho e ON e.id_escala = c.id_escala
WHERE c.id_funcionario = p_func
GROUP BY e.dia_semana
HAVING COUNT(*) > 1
LIMIT 1;
IF v_dia IS NOT NULL THEN RAISE EXCEPTION 'O funcionário % não pode ter duas escalas em %.',
p_func,
v_dia;
END IF;
SELECT COALESCE(
        SUM(
            EXTRACT(
                EPOCH
                FROM (e.horario_saida - e.horario_entrada)
            ) / 3600
        ),
        0
    ) INTO v_horas
FROM Cumpre c
    JOIN Escala_Trabalho e ON e.id_escala = c.id_escala
WHERE c.id_funcionario = p_func;
IF v_horas > 50 THEN RAISE EXCEPTION 'RN12: a carga semanal do funcionário % seria de %h (máximo 50h).',
p_func,
ROUND(v_horas, 2);
END IF;
IF p_checa_minimo
AND v_horas = 0
AND EXISTS (
    SELECT 1
    FROM Funcionario
    WHERE id_funcionario = p_func
) THEN RAISE EXCEPTION 'RN12: a carga semanal do funcionário % deve ser maior que 0h.',
p_func;
END IF;
END;
$$ LANGUAGE plpgsql;
-- Cumpre: verificação ao final da transação (permite trocar uma escala
-- por outra dentro da mesma transação sem violar temporariamente a regra)
CREATE OR REPLACE FUNCTION fn_valida_cumpre() RETURNS TRIGGER AS $$ BEGIN IF TG_OP IN ('INSERT', 'UPDATE') THEN PERFORM fn_checa_escalas_funcionario(NEW.id_funcionario, TRUE);
END IF;
IF TG_OP IN ('DELETE', 'UPDATE') THEN PERFORM fn_checa_escalas_funcionario(OLD.id_funcionario, TRUE);
END IF;
RETURN NULL;
END;
$$ LANGUAGE plpgsql;
CREATE CONSTRAINT TRIGGER tg_valida_cumpre
AFTER
INSERT
    OR
UPDATE
    OR DELETE ON Cumpre DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_valida_cumpre();
-- Escala_Trabalho: alterar horário ou dia de uma escala revalida quem a cumpre
CREATE OR REPLACE FUNCTION fn_valida_alteracao_escala() RETURNS TRIGGER AS $$
DECLARE r RECORD;
BEGIN FOR r IN
SELECT id_funcionario
FROM Cumpre
WHERE id_escala = NEW.id_escala LOOP PERFORM fn_checa_escalas_funcionario(r.id_funcionario, FALSE);
END LOOP;
RETURN NULL;
END;
$$ LANGUAGE plpgsql;
CREATE CONSTRAINT TRIGGER tg_valida_alteracao_escala
AFTER
UPDATE OF dia_semana,
    horario_entrada,
    horario_saida ON Escala_Trabalho DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fn_valida_alteracao_escala();
-- ---------------------------------------------------------------------
-- Especialização disjunta de Solicitacao
--   uma solicitação não pode ser ao mesmo tempo Justificativa_Atraso e Abono_Falta
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_valida_disjuncao_solicitacao() RETURNS TRIGGER AS $$ BEGIN IF TG_TABLE_NAME = 'abono_falta' THEN IF EXISTS (
        SELECT 1
        FROM Justificativa_Atraso
        WHERE id_solic = NEW.id_solic
    ) THEN RAISE EXCEPTION 'A solicitação % já é uma justificativa de atraso.',
    NEW.id_solic;
END IF;
ELSE IF EXISTS (
    SELECT 1
    FROM Abono_Falta
    WHERE id_solic = NEW.id_solic
) THEN RAISE EXCEPTION 'A solicitação % já é um abono de falta.',
NEW.id_solic;
END IF;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_disjuncao_abono BEFORE
INSERT
    OR
UPDATE OF id_solic ON Abono_Falta FOR EACH ROW EXECUTE FUNCTION fn_valida_disjuncao_solicitacao();
CREATE TRIGGER tg_disjuncao_justificativa BEFORE
INSERT
    OR
UPDATE OF id_solic ON Justificativa_Atraso FOR EACH ROW EXECUTE FUNCTION fn_valida_disjuncao_solicitacao();
-- ---------------------------------------------------------------------
-- Justificativa_Atraso
--   - o ponto deve ser do mesmo funcionário que submeteu a solicitação
--   - o ponto deve ter registrado atraso (minutos_atraso > 15)
--   - RN07: o ponto não pode estar em duas solicitações pendentes
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_valida_justificativa_atraso() RETURNS TRIGGER AS $$
DECLARE v_func_solic INT;
v_status VARCHAR;
v_func_ponto INT;
v_atraso INT;
BEGIN
SELECT id_funcionario,
    status INTO v_func_solic,
    v_status
FROM Solicitacao
WHERE id_solic = NEW.id_solic;
SELECT id_funcionario,
    minutos_atraso INTO v_func_ponto,
    v_atraso
FROM Ponto
WHERE id_registro = NEW.id_registro;
IF v_func_solic <> v_func_ponto THEN RAISE EXCEPTION 'O ponto % não pertence ao funcionário que submeteu a solicitação %.',
NEW.id_registro,
NEW.id_solic;
END IF;
IF v_atraso <= 15 THEN RAISE EXCEPTION 'O ponto % não registrou atraso (minutos_atraso = %, precisa ser > 15).',
NEW.id_registro,
v_atraso;
END IF;
IF v_status = 'pendente'
AND EXISTS (
    SELECT 1
    FROM Justificativa_Atraso j
        JOIN Solicitacao s ON s.id_solic = j.id_solic
    WHERE j.id_registro = NEW.id_registro
        AND j.id_solic <> NEW.id_solic
        AND s.status = 'pendente'
) THEN RAISE EXCEPTION 'RN07: o ponto % já está em outra solicitação pendente.',
NEW.id_registro;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_valida_justificativa_atraso BEFORE
INSERT
    OR
UPDATE ON Justificativa_Atraso FOR EACH ROW EXECUTE FUNCTION fn_valida_justificativa_atraso();
-- ---------------------------------------------------------------------
-- Abona
--   - a falta deve ser do mesmo funcionário que submeteu a solicitação
--   - RN07: a falta não pode estar em duas solicitações pendentes
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_valida_abona() RETURNS TRIGGER AS $$
DECLARE v_func_solic INT;
v_status VARCHAR;
v_func_falta INT;
BEGIN
SELECT id_funcionario,
    status INTO v_func_solic,
    v_status
FROM Solicitacao
WHERE id_solic = NEW.id_solic;
SELECT id_funcionario INTO v_func_falta
FROM Falta
WHERE id_falta = NEW.id_falta;
IF v_func_solic <> v_func_falta THEN RAISE EXCEPTION 'A falta % não pertence ao funcionário que submeteu a solicitação %.',
NEW.id_falta,
NEW.id_solic;
END IF;
IF v_status = 'pendente'
AND EXISTS (
    SELECT 1
    FROM Abona a
        JOIN Solicitacao s ON s.id_solic = a.id_solic
    WHERE a.id_falta = NEW.id_falta
        AND a.id_solic <> NEW.id_solic
        AND s.status = 'pendente'
) THEN RAISE EXCEPTION 'RN07: a falta % já está em outra solicitação pendente.',
NEW.id_falta;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_valida_abona BEFORE
INSERT
    OR
UPDATE ON Abona FOR EACH ROW EXECUTE FUNCTION fn_valida_abona();
-- ---------------------------------------------------------------------
-- Solicitacao (lado da superclasse)
--   - trocar o funcionário da solicitação não pode desalinhar faltas/pontos já ligados
--   - RN07: voltar uma solicitação para 'pendente' não pode gerar duas pendentes
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_valida_solicitacao() RETURNS TRIGGER AS $$ BEGIN IF NEW.id_funcionario <> OLD.id_funcionario
    AND (
        EXISTS (
            SELECT 1
            FROM Abona a
                JOIN Falta f ON f.id_falta = a.id_falta
            WHERE a.id_solic = NEW.id_solic
                AND f.id_funcionario <> NEW.id_funcionario
        )
        OR EXISTS (
            SELECT 1
            FROM Justificativa_Atraso j
                JOIN Ponto p ON p.id_registro = j.id_registro
            WHERE j.id_solic = NEW.id_solic
                AND p.id_funcionario <> NEW.id_funcionario
        )
    ) THEN RAISE EXCEPTION 'A solicitação % tem faltas/pontos de outro funcionário.',
    NEW.id_solic;
END IF;
IF NEW.status = 'pendente'
AND OLD.status <> 'pendente'
AND (
    EXISTS (
        SELECT 1
        FROM Abona a1
            JOIN Abona a2 ON a2.id_falta = a1.id_falta
            AND a2.id_solic <> a1.id_solic
            JOIN Solicitacao s ON s.id_solic = a2.id_solic
            AND s.status = 'pendente'
        WHERE a1.id_solic = NEW.id_solic
    )
    OR EXISTS (
        SELECT 1
        FROM Justificativa_Atraso j1
            JOIN Justificativa_Atraso j2 ON j2.id_registro = j1.id_registro
            AND j2.id_solic <> j1.id_solic
            JOIN Solicitacao s ON s.id_solic = j2.id_solic
            AND s.status = 'pendente'
        WHERE j1.id_solic = NEW.id_solic
    )
) THEN RAISE EXCEPTION 'RN07: reabrir a solicitação % deixaria uma falta/ponto em duas solicitações pendentes.',
NEW.id_solic;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER tg_valida_solicitacao BEFORE
UPDATE OF status,
    id_funcionario ON Solicitacao FOR EACH ROW EXECUTE FUNCTION fn_valida_solicitacao();
COMMIT;