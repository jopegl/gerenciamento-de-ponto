BEGIN;
CREATE TABLE Departamento (
    id_departamento INT GENERATED BY DEFAULT AS IDENTITY,
    nome_departamento VARCHAR(100) NOT NULL,
    CONSTRAINT pk_departamento PRIMARY KEY (id_departamento),
    CONSTRAINT uq_departamento_nome UNIQUE (nome_departamento)
);
CREATE TABLE Cargo (
    id_cargo INT GENERATED BY DEFAULT AS IDENTITY,
    nome_cargo VARCHAR(100) NOT NULL,
    descricao VARCHAR(255),
    CONSTRAINT pk_cargo PRIMARY KEY (id_cargo),
    CONSTRAINT uq_cargo_nome UNIQUE (nome_cargo)
);
CREATE TABLE Escala_Trabalho (
    id_escala INT GENERATED BY DEFAULT AS IDENTITY,
    descricao VARCHAR(255),
    dia_semana INT NOT NULL,
    horario_entrada TIME NOT NULL,
    horario_saida TIME NOT NULL,
    CONSTRAINT pk_escala_trabalho PRIMARY KEY (id_escala),
    CONSTRAINT ck_escala_dia_semana CHECK (dia_semana IN (0, 1, 2, 3, 4, 5, 6)),
    -- domingo, segunda, terça, quarta, quinta, sexta, sábado
    CONSTRAINT ck_escala_horario CHECK (horario_saida > horario_entrada)
);
CREATE TABLE Funcionario (
    id_funcionario INT GENERATED BY DEFAULT AS IDENTITY,
    cpf CHAR(11) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    sexo CHAR(1) NOT NULL,
    email VARCHAR(150) NOT NULL,
    data_admissao DATE NOT NULL,
    id_departamento INT NOT NULL,
    id_cargo INT NOT NULL,
    id_gerente INT,
    CONSTRAINT pk_funcionario PRIMARY KEY (id_funcionario),
    CONSTRAINT uq_funcionario_cpf UNIQUE (cpf),
    CONSTRAINT uq_funcionario_email UNIQUE (email),
    CONSTRAINT ck_funcionario_cpf CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_funcionario_sexo CHECK (sexo IN ('M', 'F')),
    CONSTRAINT ck_funcionario_gerente CHECK (id_gerente <> id_funcionario),
    CONSTRAINT fk_funcionario_departamento FOREIGN KEY (id_departamento) REFERENCES Departamento (id_departamento) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_funcionario_cargo FOREIGN KEY (id_cargo) REFERENCES Cargo (id_cargo) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE Gerente_RH (
    id_funcionario INT,
    CONSTRAINT pk_gerente_rh PRIMARY KEY (id_funcionario),
    CONSTRAINT fk_gerente_rh_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
ALTER TABLE Funcionario
ADD CONSTRAINT fk_funcionario_gerente FOREIGN KEY (id_gerente) REFERENCES Gerente_RH (id_funcionario) ON UPDATE CASCADE ON DELETE
SET NULL;
CREATE TABLE Admin (
    id_gerente INT,
    CONSTRAINT pk_admin PRIMARY KEY (id_gerente),
    CONSTRAINT fk_admin_gerente_rh FOREIGN KEY (id_gerente) REFERENCES Gerente_RH (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Gerencia_RH (
    id_admin INT,
    id_gerente INT,
    CONSTRAINT pk_gerencia_rh PRIMARY KEY (id_admin, id_gerente),
    CONSTRAINT fk_gerencia_rh_admin FOREIGN KEY (id_admin) REFERENCES Admin (id_gerente) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_gerencia_rh_gerente FOREIGN KEY (id_gerente) REFERENCES Gerente_RH (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Contato_Emergencia (
    id_contato INT GENERATED BY DEFAULT AS IDENTITY,
    nome_contato VARCHAR(150) NOT NULL,
    telefone_contato VARCHAR(20) NOT NULL,
    parentesco VARCHAR(50) NOT NULL,
    id_funcionario INT NOT NULL,
    CONSTRAINT pk_contato_emergencia PRIMARY KEY (id_contato),
    CONSTRAINT fk_contato_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Funcionario_Telefone (
    id_funcionario INT,
    telefone VARCHAR(20),
    CONSTRAINT pk_funcionario_telefone PRIMARY KEY (id_funcionario, telefone),
    CONSTRAINT fk_telefone_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Cumpre (
    id_funcionario INT,
    id_escala INT,
    status VARCHAR(10) NOT NULL DEFAULT 'pendente',
    CONSTRAINT pk_cumpre PRIMARY KEY (id_funcionario, id_escala),
    CONSTRAINT ck_cumpre_status CHECK (status IN ('pendente', 'aprovada')),
    CONSTRAINT fk_cumpre_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_cumpre_escala FOREIGN KEY (id_escala) REFERENCES Escala_Trabalho (id_escala) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE Ponto (
    id_registro INT GENERATED BY DEFAULT AS IDENTITY,
    data_registro DATE NOT NULL,
    hora_entrada TIME NOT NULL,
    hora_saida TIME,
    minutos_atraso INT NOT NULL DEFAULT 0,
    id_funcionario INT NOT NULL,
    CONSTRAINT pk_ponto PRIMARY KEY (id_registro),
    CONSTRAINT uq_ponto_funcionario_data UNIQUE (id_funcionario, data_registro),
    CONSTRAINT ck_ponto_horario CHECK (
        hora_saida IS NULL
        OR hora_saida > hora_entrada
    ),
    CONSTRAINT ck_ponto_minutos_atraso CHECK (minutos_atraso >= 0),
    CONSTRAINT fk_ponto_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Pausa (
    id_pausa INT GENERATED BY DEFAULT AS IDENTITY,
    hora_inicio TIME NOT NULL,
    hora_fim TIME,
    id_registro INT NOT NULL,
    CONSTRAINT pk_pausa PRIMARY KEY (id_pausa),
    CONSTRAINT ck_pausa_horario CHECK (
        hora_fim IS NULL
        OR hora_fim > hora_inicio
    ),
    CONSTRAINT fk_pausa_ponto FOREIGN KEY (id_registro) REFERENCES Ponto (id_registro) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Hora_Extra (
    id_hora_extra INT GENERATED BY DEFAULT AS IDENTITY,
    quantidade NUMERIC(4, 2) NOT NULL,
    id_registro INT NOT NULL,
    CONSTRAINT pk_hora_extra PRIMARY KEY (id_hora_extra),
    CONSTRAINT ck_hora_extra_quantidade CHECK (quantidade > 0),
    CONSTRAINT fk_hora_extra_ponto FOREIGN KEY (id_registro) REFERENCES Ponto (id_registro) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Periodo_Ausencia (
    id_periodo INT GENERATED BY DEFAULT AS IDENTITY,
    tipo VARCHAR(10) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    id_funcionario INT NOT NULL,
    CONSTRAINT pk_periodo_ausencia PRIMARY KEY (id_periodo),
    CONSTRAINT uq_periodo_funcionario_inicio UNIQUE (id_funcionario, data_inicio),
    CONSTRAINT ck_periodo_tipo CHECK (tipo IN ('ferias', 'folga', 'licenca')),
    CONSTRAINT ck_periodo_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT fk_periodo_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Falta (
    id_falta INT GENERATED BY DEFAULT AS IDENTITY,
    data_falta DATE NOT NULL,
    status_justificativa VARCHAR(20) NOT NULL DEFAULT 'pendente',
    id_funcionario INT NOT NULL,
    id_gerente INT NOT NULL,
    CONSTRAINT pk_falta PRIMARY KEY (id_falta),
    CONSTRAINT uq_falta_funcionario_data UNIQUE (id_funcionario, data_falta),
    CONSTRAINT ck_falta_status CHECK (
        status_justificativa IN ('pendente', 'abonada', 'sem_justificativa')
    ),
    CONSTRAINT fk_falta_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_falta_gerente FOREIGN KEY (id_gerente) REFERENCES Gerente_RH (id_funcionario) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE Solicitacao (
    id_solic INT GENERATED BY DEFAULT AS IDENTITY,
    data_solic DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(10) NOT NULL DEFAULT 'pendente',
    descricao VARCHAR(500),
    id_funcionario INT NOT NULL,
    id_gerente INT,
    CONSTRAINT pk_solicitacao PRIMARY KEY (id_solic),
    CONSTRAINT ck_solicitacao_status CHECK (status IN ('pendente', 'deferida', 'indeferida')),
    CONSTRAINT ck_solicitacao_analise CHECK (
        status = 'pendente'
        OR id_gerente IS NOT NULL
    ),
    CONSTRAINT fk_solicitacao_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_solicitacao_gerente FOREIGN KEY (id_gerente) REFERENCES Gerente_RH (id_funcionario) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE Justificativa_Atraso (
    id_solic INT,
    id_registro INT,
    CONSTRAINT pk_justificativa_atraso PRIMARY KEY (id_solic, id_registro),
    CONSTRAINT fk_justificativa_solicitacao FOREIGN KEY (id_solic) REFERENCES Solicitacao (id_solic) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_justificativa_ponto FOREIGN KEY (id_registro) REFERENCES Ponto (id_registro) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Abono_Falta (
    id_solic INT,
    CONSTRAINT pk_abono_falta PRIMARY KEY (id_solic),
    CONSTRAINT fk_abono_solicitacao FOREIGN KEY (id_solic) REFERENCES Solicitacao (id_solic) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Abona (
    id_solic INT,
    id_falta INT,
    CONSTRAINT pk_abona PRIMARY KEY (id_solic, id_falta),
    CONSTRAINT fk_abona_abono_falta FOREIGN KEY (id_solic) REFERENCES Abono_Falta (id_solic) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_abona_falta FOREIGN KEY (id_falta) REFERENCES Falta (id_falta) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Anexo_Comprovante (
    id_anexo INT GENERATED BY DEFAULT AS IDENTITY,
    caminho_comprovante VARCHAR(500) NOT NULL,
    formato VARCHAR(10) NOT NULL,
    tamanho_mb NUMERIC(6, 2) NOT NULL,
    id_solic INT NOT NULL,
    CONSTRAINT pk_anexo_comprovante PRIMARY KEY (id_anexo),
    CONSTRAINT uq_anexo_caminho UNIQUE (caminho_comprovante),
    CONSTRAINT fk_anexo_solicitacao FOREIGN KEY (id_solic) REFERENCES Solicitacao (id_solic) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE Notificacao (
    id_notificacao INT GENERATED BY DEFAULT AS IDENTITY,
    tipo VARCHAR(20) NOT NULL,
    mensagem VARCHAR(500) NOT NULL,
    data TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lida BOOLEAN NOT NULL DEFAULT FALSE,
    id_funcionario INT NOT NULL,
    CONSTRAINT pk_notificacao PRIMARY KEY (id_notificacao),
    CONSTRAINT ck_notificacao_tipo CHECK (
        tipo IN (
            'atraso',
            'falta',
            'limite_faltas',
            'resultado_analise'
        )
    ),
    CONSTRAINT fk_notificacao_funcionario FOREIGN KEY (id_funcionario) REFERENCES Funcionario (id_funcionario) ON UPDATE CASCADE ON DELETE CASCADE
);
COMMIT